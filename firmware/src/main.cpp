static const char* resetReasonName() {
  switch (esp_reset_reason()) {
    case ESP_RST_POWERON: return "power on";
    case ESP_RST_SW: return "software restart";
    case ESP_RST_PANIC: return "crash (panic)";
    case ESP_RST_INT_WDT: return "crash (interrupt watchdog)";
    case ESP_RST_TASK_WDT: return "crash (task watchdog)";
    case ESP_RST_WDT: return "crash (watchdog)";
    case ESP_RST_BROWNOUT: return "brown-out (power dip)";
    case ESP_RST_DEEPSLEEP: return "deep sleep";
    case ESP_RST_USB: return "USB";
    default: return "other";
  }
}

// snprintf onto the end of a JSON buffer, clamped: n never runs past cap, so a long
// status line can't turn "cap - n" into a huge number (a buffer overrun).
static size_t jcat(char* out, size_t cap, size_t n, const char* fmt, ...) __attribute__((format(printf, 4, 5)));
static size_t jcat(char* out, size_t cap, size_t n, const char* fmt, ...) {
  if (n >= cap) return cap - 1;
  va_list ap; va_start(ap, fmt);
  int m = vsnprintf(out + n, cap - n, fmt, ap);
  va_end(ap);
  if (m < 0) return n;
  n += (size_t)m;
  return n >= cap ? cap - 1 : n;
}

