// Wi-Fi transmit power. ESP32-C3 Super Mini boards have a poor antenna match:
// at full power many phones struggle to join or drop out, and the current
// spikes can brown out a weak USB supply. 8.5 dBm is the well-known fix there
// (and was for Skipper Flipper); S3 boards default to 15 dBm.
static const wifi_power_t TXP_LEVELS[3] = {WIFI_POWER_8_5dBm, WIFI_POWER_15dBm, WIFI_POWER_19_5dBm};
static const char* TXP_NAMES[3] = {"8.5", "15", "19.5"};
static void applyTxPower() {
  if (cfg.txp > 2) cfg.txp = TXP_DEFAULT;
  WiFi.setTxPower(TXP_LEVELS[cfg.txp]);
  blog::logf("Wi-Fi transmit power %s dBm", TXP_NAMES[cfg.txp]);
}

// Who joins and leaves the hotspot, and why (reason codes: 2 = auth expired,
// 4/15 = inactivity/handshake timeout, 8 = left, 200+ = beacon/handshake).
static void onWifiEvent(arduino_event_id_t e, arduino_event_info_t info) {
  switch (e) {
    case ARDUINO_EVENT_WIFI_AP_STACONNECTED: {
      const uint8_t* m = info.wifi_ap_staconnected.mac;
      blog::logf("Wi-Fi: device ..%02X:%02X joined (aid %u), %d on the hotspot", m[4], m[5], info.wifi_ap_staconnected.aid, WiFi.softAPgetStationNum());
      break;
    }
    case ARDUINO_EVENT_WIFI_AP_STADISCONNECTED: {
      const uint8_t* m = info.wifi_ap_stadisconnected.mac;
      blog::logf("Wi-Fi: device ..%02X:%02X left, reason %u, %d on the hotspot", m[4], m[5], info.wifi_ap_stadisconnected.reason, WiFi.softAPgetStationNum());
      break;
    }
    case ARDUINO_EVENT_WIFI_AP_STAIPASSIGNED:
      blog::logf("Wi-Fi: gave out %s", IPAddress(info.wifi_ap_staipassigned.ip.addr).toString().c_str());
      break;
    default: break;
  }
}

static void wifiBegin() {
  WiFi.onEvent(onWifiEvent);
  WiFi.persistent(false);
  WiFi.mode(WIFI_AP);
  WiFi.softAPConfig(IPAddress(192, 168, 4, 1), IPAddress(192, 168, 4, 1), IPAddress(255, 255, 255, 0));
  WiFi.softAP(cfg.ssid, cfg.pass, AP_CHANNEL, 0, AP_MAX_CLIENTS);
  WiFi.setSleep(false);                       // no modem power-save: it adds tens of ms to every packet
  applyTxPower();
  dns.setErrorReplyCode(DNSReplyCode::NoError);
  dns.start(53, "*", WiFi.softAPIP());
}

