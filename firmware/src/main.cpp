static void redirectHome(AsyncWebServerRequest* r) {
  probeReqs++;
  AsyncWebServerResponse* resp = r->beginResponse(302, "text/plain", "");
  resp->addHeader("Location", String("http://") + WiFi.softAPIP().toString() + "/");
  r->send(resp);
}

static void onWsEvent(AsyncWebSocket* srv, AsyncWebSocketClient* client, AwsEventType type,
                      void* arg, uint8_t* data, size_t len) {
  (void)data; (void)len;
  if (type == WS_EVT_CONNECT) {
    client->client()->setNoDelay(true);      // send small audio packets now, don't batch them (Nagle)
    static char buf[STATUS_BUF]; statusJson(buf, sizeof buf);   // static: web-task stack stays small (one web task)
    client->text(buf);
    blog::logf("page #%lu connected from %s, %u page(s) open", (unsigned long)client->id(), client->remoteIP().toString().c_str(), (unsigned)srv->count());
  } else if (type == WS_EVT_DISCONNECT) {
    blog::logf("page #%lu disconnected", (unsigned long)client->id());
  } else if (type == WS_EVT_ERROR) {
    blog::logf("page #%lu error %u", (unsigned long)client->id(), arg ? *(uint16_t*)arg : 0);
  }
}

