// Start the enable-config → mode → end-config sequence; radarCmdTick() sends
// one step every 200 ms from loop(), so nothing blocks and the web task never
// touches the UART. Frames pause for ~0.6 s while it runs.
static void radarSendMode() {
#if RADAR_LD2450
  cmdStep = 0;                                  // the LD2450 has no RD-03D mode commands; Single is done in firmware
#else
  cmdStep = 1; cmdStepMs = millis() - 200;
#endif
}

static void radarCmdTick() {
  if (!cmdStep || millis() - cmdStepMs < 200) return;
  switch (cmdStep) {
    case 1: radarSerial.write(rd03d::CMD_ENABLE_CONFIG, sizeof rd03d::CMD_ENABLE_CONFIG); break;
    case 2: radarSerial.write(cfg.multi ? rd03d::CMD_MULTI_TARGET : rd03d::CMD_SINGLE_TARGET, 12); break;
    case 3: radarSerial.write(rd03d::CMD_END_CONFIG, sizeof rd03d::CMD_END_CONFIG); break;
    default: cmdStep = 0; return;                  // the parser resyncs on the next AA FF 03 00 by itself
  }
  cmdStepMs = millis();
  cmdStep++;
}

static void radarBegin() {
  radarSerial.setRxBufferSize(1024);
  radarSerial.begin(RADAR_BAUD, SERIAL_8N1, PIN_RADAR_RX, PIN_RADAR_TX);
  delay(100);
  radarSendMode();
}

static bool radarWanted() { return !(cfg.stetho && cfg.radarOff) && !radarAsleep; }

static bool radarAlive() { return radarPowered && lastFrameMs && (millis() - lastFrameMs) < 1500; }

// Optional high-side switch on the radar's 5 V (see config.h).
static void radarPower(bool on) {
#if PIN_RADAR_PWR >= 0
  if (on == radarPowered) return;
  digitalWrite(PIN_RADAR_PWR, on ? HIGH : LOW);
  radarPowered = on;
  tracker.reset();
  if (on) { radarSendMode(); cmdStepMs = millis(); }     // re-send the mode once it has booted (first step after 200 ms)
#else
  (void)on;
#endif
}

// Settings -> gate + tracker options (cheap; called every frame so a change applies at once)
static void applyFilterCfg() {
  gate.cfg.minMm = (uint16_t)cfg.minRangeCm * 10;
  gate.cfg.maxDeg = cfg.edgeDeg;
  gate.cfg.handheld = cfg.handheld;
  gate.cfg.stuckS = cfg.stuckS;
  tracker.cfg.noClutter = cfg.handheld;
  tracker.cfg.strictGhost = cfg.strictGhost;
}

static void radarPoll() {
  while (radarSerial.available()) {
    uint8_t b = (uint8_t)radarSerial.read();
    if (parser.feed(b, frame)) {
      uint32_t t = millis();
      float gdt = prevFrameMs ? (t - prevFrameMs) / 1000.0f : 0.05f;
      applyFilterCfg();
      rd03d::Frame before = frame;
      gate.apply(frame, gdt);
      gateDropN = 0;
      for (int i = 0; i < rd03d::MAX_TARGETS; i++)
        if (before.t[i].present && gate.why(i) != blip_gate::KEEP)
          gateDrop[gateDropN++] = {before.t[i].x_mm, before.t[i].y_mm, (uint8_t)gate.why(i)};
      if (!cfg.multi) rd03d::keep_nearest(frame);   // Single mode: the LD2450 always sends three, so pick here
      if (cfg.filter == 1) {
        float dt = prevFrameMs ? (t - prevFrameMs) / 1000.0f : 0.05f;
        tracker.update(frame, dt);
        tracker.visible(shown, shownIds);
      } else {
        shown = frame;
        for (int i = 0; i < rd03d::MAX_TARGETS; i++) shownIds[i] = i + 1;
      }
      prevFrameMs = lastFrameMs = t;
      frameCount1s++;
    }
  }
  uint32_t now = millis();
  if (now - fpsWindowStart >= 1000) { fps = frameCount1s; frameCount1s = 0; fpsWindowStart = now; }
}

