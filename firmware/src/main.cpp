static uint32_t lastWsMs = 0, lastLedMs = 0, lastStatusPushMs = 0, lastHealthMs = 0;
static uint32_t lastTargetsFrames = 0;


// Fires the instant ANY heap allocation fails, anywhere in the firmware or a
// library (AsyncTCP, lwIP, ...). Logs the size, memory-type and the calling
// function so a sudden crash has a concrete "who asked for what" right
// before it, instead of just a watchdog panic with no lead. No heap use here.
static void onAllocFailed(size_t size, uint32_t caps, const char* fn) {
  blog::logf("ALLOC FAILED: %u bytes (caps 0x%lx) in %s (%lu KB free, biggest block %lu)", (unsigned)size, (unsigned long)caps, fn,
             (unsigned long)(ESP.getFreeHeap() / 1024), (unsigned long)(heap_caps_get_largest_free_block(MALLOC_CAP_8BIT) / 1024));
}

void setup() {
  if (bootMagic != 0xB11B0001u || esp_reset_reason() == ESP_RST_POWERON) { bootMagic = 0xB11B0001u; bootCount = 0; }
  bootCount++;
  heap_caps_register_failed_alloc_callback(onAllocFailed);
  Serial.begin(115200);
#if defined(CONFIG_IDF_TARGET_ESP32S3) && !ARDUINO_USB_CDC_ON_BOOT
  usbLog().setTxTimeoutMs(0);      // S3 boards wired to the chip's own USB (no CH343): copy the log there too, never block
  usbLog().begin();
#endif
#if ARDUINO_USB_CDC_ON_BOOT && ARDUINO_USB_MODE
  Serial.setTxTimeoutMs(0);     // USB serial: never wait for a PC that isn't reading
#endif
  delay(200);
  blog::begin(esp_reset_reason() != ESP_RST_POWERON);
  Serial.println();
  blog::logf("=== Blip %s built %s on %s, start #%lu, last reset: %s ===", BLIP_VERSION, BUILD_DATE, BLIP_BOARD,
             (unsigned long)bootCount, resetReasonName());

#if PIN_STATUS_LED >= 0
  pinMode(PIN_STATUS_LED, OUTPUT);
#endif
#if PIN_RADAR_PWR >= 0
  pinMode(PIN_RADAR_PWR, OUTPUT);
  digitalWrite(PIN_RADAR_PWR, HIGH);
#endif
#if PIN_STETHO_PWR >= 0
  pinMode(PIN_STETHO_PWR, OUTPUT);
  digitalWrite(PIN_STETHO_PWR, LOW);               // applyStetho() switches it on if Stetho is enabled
  stethoPowered = false;
#endif
  loadSettings();
  wifiBegin();
  radarBegin();
  oled.begin((OledKind)cfg.oled);
  applyStetho();
  webBegin();
  blog::logf("hotspot '%s' on channel %d -> http://%s/  (%lu KB free)", cfg.ssid, AP_CHANNEL, WiFi.softAPIP().toString().c_str(),
             (unsigned long)(ESP.getFreeHeap() / 1024));
}

void loop() {
  loopStartUs = micros();
  if (!(lab::f.skip & 4)) dns.processNextRequest();
  if (!(lab::f.skip & 1)) { radarCmdTick(); radarPoll(); }
  sleepTick();
  ws.cleanupClients();

  uint32_t now = millis();

  // Targets to the phone(s)
  bool fresh = parser.frames() != lastTargetsFrames;
  if (!(lab::f.text & 1) && ws.count() > 0 && ((fresh && now - lastWsMs >= WS_TARGET_RATE_MS) || now - lastWsMs >= 1000)) {
    lastWsMs = now; lastTargetsFrames = parser.frames();
    char buf[1200]; size_t n = targetsJson(buf, sizeof buf);
    ws.textAll(buf, n);
  }

  // Status (incl. Stetho diagnostics) pushed every 2 s, so the page doesn't
  // have to open a new HTTP connection every second to ask for it.
  if (!(lab::f.text & 2) && ws.count() > 0 && now - lastStatusPushMs >= 2000) {
    lastStatusPushMs = now;
    static char sb[STATUS_BUF]; size_t sn = statusJson(sb, sizeof sb);
    ws.textAll(sb, sn);
  }

  // Stetho settings changed on the web page
  if (labRestart) { labRestart = false; if (stetho.running()) stetho.stop(); stethoPending = true; }   // Lab: new source / priority
  if (labClearStats) { labClearStats = false; stetho.clearStats(); loopMaxUs = 0; loopMaxShownUs = 0; }
  if (stethoPending) { stethoPending = false; applyStetho(); }

  // Stetho packets to the phone(s). This is the 0.2.2-pre send logic that ran
  // for minutes on a real C3, put back as an A/B test: the latency rework
  // called ws.binaryAll() on every packet and let a small (8) queue refuse
  // them, which kept loopTask inside AsyncWebSocket's client/queue locks and
  // lwIP's tcp_write dozens of times a second — the same locks async_tcp
  // needs, and where the decoded crash found loopTask. So again: only send
  // when every phone's queue has room (availableForWriteAll), only the newest
  // two packets per pass, and throw away a backlog of six (~190 ms) so audio
  // stays fresh rather than late. Packets stay mu-law / 32 ms.
  if (stetho.running()) {
    static uint8_t pk[6][PKT_HDR + AUDIO_FRAME];
    static size_t pl[6];
    int got = 0;
    while (got < 6 && (pl[got] = stetho.nextAudioPacket(pk[got], sizeof pk[got])) > 0) got++;
    if (got == 6) stetho.flushAudio();
    uint8_t vb[PKT_HDR + VITALS_FRAME * 2]; size_t vl;
    if (lab::f.send == 1) {                                 // Lab: audio drained and thrown away, nothing sent
      while (stetho.nextVitalsPacket(vb, sizeof vb) > 0) {}
    } else if (lab::f.send == 2) {                          // Lab: every packet straight into binaryAll(), no room check
      if (ws.count() > 0) {
        for (int i = 0; i < got; i++) { ws.binaryAll(pk[i], pl[i]); stethoSent++; }
        while ((vl = stetho.nextVitalsPacket(vb, sizeof vb)) > 0) ws.binaryAll(vb, vl);
      } else {
        while (stetho.nextVitalsPacket(vb, sizeof vb) > 0) {}
      }
    } else if (ws.count() > 0) {
      for (int i = (got > 2 ? got - 2 : 0); i < got; i++) {
        if (!ws.availableForWriteAll()) { stethoSkipped += got - i; break; }
        ws.binaryAll(pk[i], pl[i]);
        stethoSent++;
      }
      if (got > 2) stethoSkipped += got - 2;
      while ((vl = stetho.nextVitalsPacket(vb, sizeof vb)) > 0) if (ws.availableForWriteAll()) ws.binaryAll(vb, vl);
    } else {
      while (stetho.nextVitalsPacket(vb, sizeof vb) > 0) {}
    }
  }

  // Node health for the Stetho tab: slowest loop() pass and free memory
  uint32_t passUs = micros() - loopStartUs;
  if (passUs > loopMaxUs) loopMaxUs = passUs;
  if (now - lastHealthMs >= 5000) { lastHealthMs = now; loopMaxShownUs = loopMaxUs; loopMaxUs = 0; }
  // A single pass over 150 ms would already explain a missed watchdog
  // check-in on its own; log it the instant it happens, not at the next
  // health tick, so a stall shows up even if the reset comes first.
  static uint32_t lastSlowLogMs = 0;
  if (passUs > 150000 && now - lastSlowLogMs >= 500) {
    lastSlowLogMs = now;
    blog::logf("SLOW LOOP: one pass took %lu ms (heap %lu KB)", (unsigned long)(passUs / 1000), (unsigned long)(ESP.getFreeHeap() / 1024));
  }

  // Health line in the node log every 10 s: memory (free, lowest, biggest
  // block), who is connected, request counts and the Stetho numbers, so a slow
  // leak or a Wi-Fi drop can be read back from /api/log after the fact.
  // While Stetho is running, every 1 s instead: the last two crashes happened
  // 4-9 s after Stetho started, too fast for a 10 s line to ever catch
  // more than one reading before the reset.
  static uint32_t lastHealthLogMs = 0, lastHttp = 0, lastProbe = 0, lastSent = 0, lastSkip = 0, lastDrop = 0;
  static bool lowWarned = false;
  uint32_t healthEveryMs = (cfg.stetho && stetho.running()) ? 1000 : 10000;
  if (now - lastHealthLogMs >= healthEveryMs) {
    lastHealthLogMs = now;
    uint32_t heap = ESP.getFreeHeap();
    char st[200] = "Stetho off";
    if (cfg.stetho) {
      int a, b, c; stetho.level(a, b, c);
      snprintf(st, sizeof st, "Stetho %s %d mV, +%lu sent +%lu skipped +%lu dropped, block %lu/%lu us, gap max %lu ms, read timeouts %lu",
               stetho.running() ? "on" : (stethoAsleep ? "asleep" : "NOT running"),
               b, (unsigned long)(stethoSent - lastSent), (unsigned long)(stethoSkipped - lastSkip), (unsigned long)(stetho.dropped() - lastDrop),
               (unsigned long)stetho.dspUsAvg(), (unsigned long)stetho.dspUsMax(), (unsigned long)stetho.gapMaxMs(), (unsigned long)stetho.readTimeouts());
    }
    // async_tcp's own state: if it ever stops checking in with the watchdog,
    // this is the one thing a loopTask-only crash dump can't show — whether
    // it was genuinely busy (Running/Ready, pegging the CPU) or stuck waiting
    // on something that never arrived (Blocked), at the last health tick
    // before a crash. "?" if the library hasn't started that task yet.
    char tcpSt[40] = "async_tcp ?";
    if (TaskHandle_t h = xTaskGetHandle("async_tcp")) {
      static const char* NAMES[] = {"Running", "Ready", "Blocked", "Suspended", "Deleted", "Invalid"};
      eTaskState st2 = eTaskGetState(h);
      snprintf(tcpSt, sizeof tcpSt, "async_tcp %s, stack free %u", (st2 >= 0 && st2 <= eInvalid) ? NAMES[st2] : "?",
               (unsigned)uxTaskGetStackHighWaterMark(h));
    }
    blog::logf("health: %lu KB free (lowest %lu, biggest block %lu) | %d on hotspot, %u page(s) | +%lu requests +%lu probes | loop %lu ms | %s | %s",
               (unsigned long)(heap / 1024), (unsigned long)(ESP.getMinFreeHeap() / 1024),
               (unsigned long)(heap_caps_get_largest_free_block(MALLOC_CAP_8BIT) / 1024), WiFi.softAPgetStationNum(), (unsigned)ws.count(),
               (unsigned long)(httpReqs - lastHttp), (unsigned long)(probeReqs - lastProbe), (unsigned long)(loopMaxShownUs / 1000), st, tcpSt);
    lastHttp = httpReqs; lastProbe = probeReqs; lastSent = stethoSent; lastSkip = stethoSkipped; lastDrop = stetho.dropped();
    if (heap < 40 * 1024 && !lowWarned) { lowWarned = true; blog::logf("WARNING: memory low (%lu KB free)", (unsigned long)(heap / 1024)); }
    if (heap > 60 * 1024) lowWarned = false;
  }
  if (txpPending) { txpPending = false; applyTxPower(); }

  // OLED mirror (re-init here, not in the web task, so I2C is only touched from loop())
  if (oledPending) { oledPending = false; oled.begin((OledKind)cfg.oled); }
  if (!(lab::f.skip & 2)) oled.draw(shown, radarAlive(), radarAsleep, cfg.filter == 1, WiFi.softAPgetStationNum(), WiFi.softAPIP().toString().c_str());

  // Status LED: slow blink = waiting for radar, fast blink = frames flowing
#if PIN_STATUS_LED >= 0
  uint32_t period = radarAlive() ? 150 : 1000;
  if (now - lastLedMs >= period) {
    lastLedMs = now;
    static bool on = false; on = !on;
    digitalWrite(PIN_STATUS_LED, (on ^ STATUS_LED_INVERTED) ? HIGH : LOW);
  }
#endif

  // Lab: pace the loop. 0 (shipped) = free-running; the bench test, which survives, sleeps 1 ms per pass.
  if (lab::f.pace == 1) delay(1);
  else if (lab::f.pace == 2) delay(10);
}
