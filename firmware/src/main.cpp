static size_t targetsJson(char* out, size_t cap) {
  size_t n = snprintf(out, cap, "{\"ms\":%lu,\"alive\":%s,\"fps\":%lu,\"f\":\"%s\",\"sleep\":%s,\"t\":[",
                      (unsigned long)millis(), radarAlive() ? "true" : "false", (unsigned long)fps,
                      cfg.filter == 1 ? "smart" : "raw", radarAsleep ? "true" : "false");
  bool first = true;
  for (int i = 0; i < rd03d::MAX_TARGETS; i++) {
    const rd03d::Target& t = shown.t[i];
    if (!t.present || !radarAlive()) continue;
    float d = sqrtf((float)t.x_mm * t.x_mm + (float)t.y_mm * t.y_mm);
    float a = atan2f((float)t.x_mm, (float)t.y_mm) * 180.0f / (float)M_PI;   // + = left
    n += snprintf(out + n, cap - n, "%s{\"id\":%d,\"x\":%d,\"y\":%d,\"v\":%d,\"res\":%u,\"d\":%.0f,\"a\":%.1f}",
                  first ? "" : ",", shownIds[i], t.x_mm, t.y_mm, t.v_cms, t.res_mm, d, a);
    first = false;
    if (n >= cap - 2) break;
  }
  n += snprintf(out + n, cap - n, "]");
  if (radarAlive() && gateDropN) {                  // what the gate dropped (any mode), for the overlay
    n += snprintf(out + n, cap - n, ",\"g\":[");
    static const char* WHY[5] = {"", "near", "edge", "scenery", "stuck"};
    for (int i = 0; i < gateDropN && n < cap - 50; i++)
      n += snprintf(out + n, cap - n, "%s{\"x\":%d,\"y\":%d,\"why\":\"%s\"}", i ? "," : "", gateDrop[i].x, gateDrop[i].y, WHY[gateDrop[i].why > 4 ? 0 : gateDrop[i].why]);
    n += snprintf(out + n, cap - n, "]");
  }
  if (cfg.handheld && radarAlive()) n += snprintf(out + n, cap - n, ",\"ego\":%.0f", gate.ego());
  if (cfg.filter == 1 && radarAlive()) {             // what the Smart filter is hiding, for the phone's overlay
    n += snprintf(out + n, cap - n, ",\"h\":[");
    bool f2 = true;
    for (int i = 0; i < blip_track::MAX_TRACKS && n < cap - 60; i++) {
      const blip_track::Track& k = tracker.track(i);
      if (!k.used || (k.st != blip_track::GHOST && k.st != blip_track::CLUTTER)) continue;
      n += snprintf(out + n, cap - n, "%s{\"id\":%u,\"x\":%.0f,\"y\":%.0f,\"why\":\"%s\"}", f2 ? "" : ",",
                    k.id, k.x, k.y, k.st == blip_track::GHOST ? "ghost" : "clutter");
      f2 = false;
    }
    n += snprintf(out + n, cap - n, "]");
  }
  n += snprintf(out + n, cap - n, "}");
  return n;
}

// Why the chip last (re)started, and how many starts since power-up: a node that
// keeps crashing shows reason "panic"/"task watchdog" and a growing count.
