#!/usr/bin/env python3
"""Blip — gzip web/index.html into firmware/include/web_ui.h (PROGMEM byte array).

Required Notice: Copyright Matthew Armstrong (https://github.com/The-Dorkknight)
Licensed under the PolyForm Noncommercial License 1.0.0. No warranty.

Run after every change to web/index.html:
    python3 tools/embed_web.py
The Flash tab (tools/flasher.py) runs it automatically before building.
"""
import gzip
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "web" / "index.html"
DST = ROOT / "firmware" / "include" / "web_ui.h"


def main() -> int:
    html = SRC.read_bytes()
    gz = gzip.compress(html, compresslevel=9, mtime=0)
    lines = []
    for i in range(0, len(gz), 16):
        lines.append("  " + ",".join(f"0x{b:02X}" for b in gz[i:i + 16]) + ",")
    body = "\n".join(lines)
    DST.write_text(
        "// GENERATED by tools/embed_web.py from web/index.html — do not edit by hand.\n"
        "// Required Notice: Copyright Matthew Armstrong (https://github.com/The-Dorkknight)\n"
        "// Licensed under the PolyForm Noncommercial License 1.0.0. No warranty.\n"
        "#pragma once\n#include <stdint.h>\n#include <stddef.h>\n"
        "#ifdef ARDUINO\n#include <pgmspace.h>\n#else\n#define PROGMEM\n#endif\n"
        f"// {len(html)} bytes of HTML -> {len(gz)} bytes gzip\n"
        f"static const size_t WEB_INDEX_GZ_LEN = {len(gz)};\n"
        "static const uint8_t WEB_INDEX_GZ[] PROGMEM = {\n" + body + "\n};\n"
    )
    print(f"embedded {SRC.name}: {len(html)} B html -> {len(gz)} B gzip -> {DST.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
